"""
VISTA — Train ResNet-50 face classifier from facial_pipeline_results.npz
=========================================================================
Loads the pre-built .npz (generated by regenerate_npz.py), performs a
correct stratified split on ORIGINAL images only, appends augmented
variants to the train split, then fine-tunes ResNet-50 for both:

    Split A : 80 % train / 10 % val / 10 % test
    Split B : 70 % train / 15 % val / 15 % test

Key correctness guarantee
--------------------------
The .npz stores 30 augmented variants per original image.  Each variant
carries metadata["augmentation_index"] in 0-29.  We split on the SET of
unique (student, source_image) pairs drawn ONLY from originals, then add
all 30 aug variants for every source image that ended up in train.
Val and test contain ONLY augmentation_index == 0 samples (one per
original image, identity-preserving crop with no stochastic transform
applied at index 0).  An assertion verifies zero leakage before training.

Outputs  (training_results/)
-----------------------------
    best_model_npz_splitA.pth
    best_model_npz_splitB.pth
    results_npz_splitA.txt
    results_npz_splitB.txt
    confusion_matrix_npz_splitA.png
    confusion_matrix_npz_splitB.png
    training_curve_npz_splitA.png
    training_curve_npz_splitB.png
    data_split_npz_log.txt

Usage:
    python train_from_npz.py [--split A|B|both] [--epochs N]
"""

