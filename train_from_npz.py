# STAGE 1 — Load .npz
# ═══════════════════════════════════════════════════════════════════════════
def load_npz(path: Path) -> dict:
    """
    Load the .npz and return a flat dict with numpy arrays plus a structured
    per-sample record list for splitting.

    Also populates the module-level KNOWN_USNS, USN_TO_IDX, NUM_CLASSES
    from the actual label set in the file.
    """
    global KNOWN_USNS, USN_TO_IDX, NUM_CLASSES

    logger.info(f"Loading .npz from {path} ...")
    if not path.exists():
        raise FileNotFoundError(
            f"NPZ not found: {path}\n"
            f"Run regenerate_npz.py first."
        )

    data     = np.load(path, allow_pickle=True)
    images   = data["images"]       # (N,160,160,3) uint8
    embs     = data["embeddings"]   # (N,512) float32
    labels   = data["labels"]       # (N,) object → str
    metadata = data["metadata"]     # (N,) object → dict

    N = images.shape[0]
    logger.info(f"  images     {images.shape}  {images.dtype}")
    logger.info(f"  embeddings {embs.shape}  {embs.dtype}")
    logger.info(f"  labels     {labels.shape}  {labels.dtype}")
    logger.info(f"  metadata   {metadata.shape}  {metadata.dtype}")
    logger.info(f"  Total samples: {N:,}")

    # Build class list from actual labels in the file (sorted for determinism)
    unique_usns = sorted(set(str(l).strip("'\"") for l in labels))
    KNOWN_USNS  = unique_usns
    USN_TO_IDX  = {usn: i for i, usn in enumerate(KNOWN_USNS)}
    NUM_CLASSES = len(KNOWN_USNS)
    logger.info(f"  Classes discovered: {NUM_CLASSES} — {KNOWN_USNS}")

    records = []
    for i in range(N):
        usn    = str(labels[i]).strip("'\"")
        meta   = metadata[i]
        if hasattr(meta, 'item'):
            meta = meta.item()
        records.append({
            "idx":     i,
            "usn":     usn,
            "cls":     USN_TO_IDX.get(usn, -1),
            "source":  str(meta.get("source_image", "")),
            "aug_idx": int(meta.get("augmentation_index", 0)),
        })

    unknown = [r for r in records if r["cls"] == -1]
    if unknown:
        bad = {r["usn"] for r in unknown}
        logger.warning(f"Unknown USNs: {bad} ({len(unknown)} samples excluded)")

    return {
        "images":     images,
        "embeddings": embs,
        "labels":     labels,
        "metadata":   metadata,
        "records":    records,
    }


# ═══════════════════════════════════════════════════════════════════════════
# STAGE 2 — Splitting
# ═══════════════════════════════════════════════════════════════════════════
def split_npz(
    records: list[dict],
    train_ratio: float,
    val_ratio:   float,
    seed: int = SEED,
) -> tuple[list[int], list[int], list[int]]:
    """
    Correct stratified split that works on SOURCE IMAGES (not samples).

    1. Collect unique (usn, source_image) pairs — these represent original photos.
    2. Split those pairs into train/val/test by ratio.
    3. train  → indices of ALL 30 aug variants from train-assigned source images.
       val    → indices where aug_idx == 0 from val-assigned source images.
       test   → indices where aug_idx == 0 from test-assigned source images.

    This guarantees:
      - val and test contain only clean (unaugmented) original crops.
      - aug variants ONLY appear in train.
      - No data leakage between splits.

    Returns:
        train_indices, val_indices, test_indices  (lists of .npz row indices)
    """
    # Group by (usn, source_image)
    source_groups: dict[tuple[str,str], list[dict]] = defaultdict(list)
    for r in records:
        if r["cls"] == -1:
            continue
        source_groups[(r["usn"], r["source"])].append(r)

    # Build a list of unique sources with their class label
    sources = sorted(source_groups.keys())           # deterministic order
    source_labels = [USN_TO_IDX[s[0]] for s in sources]

    test_ratio = round(1.0 - train_ratio - val_ratio, 6)

    # First cut: carve off test
    if test_ratio > 0:
        src_trainval, src_test, _, _ = train_test_split(
            sources, source_labels,
            test_size=test_ratio,
            stratify=source_labels,
            random_state=seed,
        )
    else:
        src_trainval, src_test = sources, []

    # Second cut: carve off val from trainval
    if val_ratio > 0 and len(src_trainval) > 1:
        tv_labels = [USN_TO_IDX[s[0]] for s in src_trainval]
        val_fraction = val_ratio / (train_ratio + val_ratio)
        src_train, src_val, _, _ = train_test_split(
            src_trainval, tv_labels,
            test_size=val_fraction,
            stratify=tv_labels,
            random_state=seed,
        )
    else:
        src_train, src_val = src_trainval, []

    src_train_set = set(src_train)
    src_val_set   = set(src_val)
    src_test_set  = set(src_test)

    # Map source keys to indices
    train_indices: list[int] = []
    val_indices:   list[int] = []
    test_indices:  list[int] = []

    for key, group in source_groups.items():
        if key in src_train_set:
            # All 30 aug variants go into train
            for r in group:
                train_indices.append(r["idx"])
        elif key in src_val_set:
            # Only aug_idx == 0 (original crop, no stochastic transform) in val
            for r in group:
                if r["aug_idx"] == 0:
                    val_indices.append(r["idx"])
        elif key in src_test_set:
            # Only aug_idx == 0 in test
            for r in group:
                if r["aug_idx"] == 0:
                    test_indices.append(r["idx"])

    return train_indices, val_indices, test_indices


def assert_no_leakage(
    train_idx: list[int],
    val_idx:   list[int],
    test_idx:  list[int],
    records:   list[dict],
    tag: str,
) -> None:
    """Assert train/val/test index sets are disjoint and val/test have aug_idx==0 only."""
    tr_set = set(train_idx)
    va_set = set(val_idx)
    te_set = set(test_idx)

    # Disjoint
    assert not tr_set & va_set, f"[{tag}] LEAKAGE: {len(tr_set & va_set)} indices in both train and val"
    assert not tr_set & te_set, f"[{tag}] LEAKAGE: {len(tr_set & te_set)} indices in both train and test"
    assert not va_set & te_set, f"[{tag}] LEAKAGE: {len(va_set & te_set)} indices in both val and test"

    # Val and test must be aug_idx==0 only
    rec_map = {r["idx"]: r for r in records}
    bad_val  = [i for i in val_idx  if rec_map[i]["aug_idx"] != 0]
    bad_test = [i for i in test_idx if rec_map[i]["aug_idx"] != 0]
    assert not bad_val,  f"[{tag}] Val contains {len(bad_val)} augmented samples (aug_idx != 0)"
    assert not bad_test, f"[{tag}] Test contains {len(bad_test)} augmented samples (aug_idx != 0)"

    logger.info(f"[{tag}] Leakage check PASSED — train/val/test disjoint, val/test are originals-only.")


def print_class_dist(
    train_idx: list[int],
    val_idx:   list[int],
    test_idx:  list[int],
    records:   list[dict],
    tag: str,
) -> None:
    rec_map = {r["idx"]: r for r in records}
    tr_cnt = defaultdict(int)
    va_cnt = defaultdict(int)
    te_cnt = defaultdict(int)
    for i in train_idx: tr_cnt[rec_map[i]["cls"]] += 1
    for i in val_idx:   va_cnt[rec_map[i]["cls"]] += 1
    for i in test_idx:  te_cnt[rec_map[i]["cls"]] += 1

    header = f"\n[{tag}] CLASS DISTRIBUTION"
    lines  = [header,
              f"  {'USN':<20} {'TRAIN':>8} {'VAL':>6} {'TEST':>6}",
              "  " + "-" * 44]
    for cls, usn in enumerate(KNOWN_USNS):
        lines.append(f"  {usn:<20} {tr_cnt[cls]:>8} {va_cnt[cls]:>6} {te_cnt[cls]:>6}")
    lines.append("  " + "-" * 44)
    lines.append(
        f"  {'TOTAL':<20} {sum(tr_cnt.values()):>8} "
        f"{sum(va_cnt.values()):>6} {sum(te_cnt.values()):>6}"
    )
    logger.info("\n".join(lines))

    # Warn thin test classes
    thin = [(KNOWN_USNS[c], n) for c, n in te_cnt.items() if n < 3]
    for usn, n in thin:
        logger.warning(f"[{tag}] WARNING: {usn} has only {n} test sample(s) — metrics will be noisy.")


