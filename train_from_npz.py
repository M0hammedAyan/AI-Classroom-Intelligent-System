# STAGE 3 — Dataset & DataLoaders
# ═══════════════════════════════════════════════════════════════════════════
class NPZFaceDataset(Dataset):
    """
    Serves (image_tensor, class_idx) pairs from pre-loaded numpy arrays.
    Images are (160,160,3) uint8 RGB — resized to 112x112 for the model.
    """
    def __init__(
        self,
        images:   np.ndarray,    # (N,160,160,3) uint8
        indices:  list[int],
        records:  list[dict],
        transform,
    ):
        self.images    = images
        self.indices   = indices
        self.rec_map   = {r["idx"]: r for r in records}
        self.transform = transform

    def __len__(self) -> int:
        return len(self.indices)

    def __getitem__(self, pos: int):
        idx   = self.indices[pos]
        label = self.rec_map[idx]["cls"]
        img   = self.images[idx]           # (160,160,3) uint8 RGB

        # Resize 160→112 (ArcFace training standard)
        img_112 = Image.fromarray(img).resize((112, 112), Image.BILINEAR)
        tensor  = self.transform(img_112)
        return tensor, label


def build_transforms(is_train: bool):
    mean = [0.5, 0.5, 0.5]
    std  = [0.5, 0.5, 0.5]
    if is_train:
        return transforms.Compose([
            transforms.RandomHorizontalFlip(p=0.3),
            transforms.ColorJitter(brightness=0.15, contrast=0.15),
            transforms.ToTensor(),
            transforms.Normalize(mean, std),
        ])
    return transforms.Compose([
        transforms.ToTensor(),
        transforms.Normalize(mean, std),
    ])


def make_loaders(
    images: np.ndarray,
    train_idx: list[int],
    val_idx:   list[int],
    test_idx:  list[int],
    records:   list[dict],
    batch_size: int = BATCH_SIZE,
):
    tr_ds  = NPZFaceDataset(images, train_idx, records, build_transforms(True))
    va_ds  = NPZFaceDataset(images, val_idx,   records, build_transforms(False))
    te_ds  = NPZFaceDataset(images, test_idx,  records, build_transforms(False))
    kwargs = dict(num_workers=0, pin_memory=False)
    return (
        DataLoader(tr_ds, batch_size=batch_size, shuffle=True,  **kwargs),
        DataLoader(va_ds, batch_size=batch_size, shuffle=False, **kwargs),
        DataLoader(te_ds, batch_size=batch_size, shuffle=False, **kwargs),
    )


# ═══════════════════════════════════════════════════════════════════════════
# STAGE 4 — Model
# ═══════════════════════════════════════════════════════════════════════════
class ResNet50FaceClassifier(nn.Module):
    """
    ResNet-50 (ImageNet init) fine-tuned for 21-class face identification.
    Frozen: conv1, bn1, layer1, layer2
    Trainable: layer3, layer4, classification head
    Input: 112x112 RGB, mean=0.5 std=0.5
    """
    def __init__(self, num_classes: int = NUM_CLASSES):
        super().__init__()
        bb = resnet50(weights=ResNet50_Weights.IMAGENET1K_V1)
        for p in bb.parameters():
            p.requires_grad = False
        for layer in (bb.layer3, bb.layer4, bb.bn1):
            for p in layer.parameters():
                p.requires_grad = True

        self.features = nn.Sequential(
            bb.conv1, bb.bn1, bb.relu, bb.maxpool,
            bb.layer1, bb.layer2, bb.layer3, bb.layer4,
            bb.avgpool,
        )
        self.head = nn.Sequential(
            nn.Flatten(),
            nn.BatchNorm1d(2048),
            nn.ReLU(inplace=True),
            nn.Dropout(0.4),
            nn.Linear(2048, 512),
            nn.BatchNorm1d(512),
            nn.ReLU(inplace=True),
            nn.Dropout(0.3),
            nn.Linear(512, num_classes),
        )
        for p in self.head.parameters():
            p.requires_grad = True

    def forward(self, x):
        return self.head(self.features(x))

    def trainable_params(self):
        return [p for p in self.parameters() if p.requires_grad]

    def n_trainable(self):
        return sum(p.numel() for p in self.parameters() if p.requires_grad)

    def n_frozen(self):
        return sum(p.numel() for p in self.parameters() if not p.requires_grad)


# ═══════════════════════════════════════════════════════════════════════════
# STAGE 5 — Train / Evaluate
# ═══════════════════════════════════════════════════════════════════════════
def train_epoch(model, loader, criterion, optimizer, device):
    model.train()
    total_loss = correct = total = 0
    for imgs, labels in loader:
        imgs, labels = imgs.to(device), labels.to(device)
        optimizer.zero_grad()
        out  = model(imgs)
        loss = criterion(out, labels)
        loss.backward()
        optimizer.step()
        total_loss += loss.item() * imgs.size(0)
        correct    += (out.argmax(1) == labels).sum().item()
        total      += imgs.size(0)
    return total_loss / max(total, 1), correct / max(total, 1)


@torch.no_grad()
def eval_epoch(model, loader, criterion, device):
    model.eval()
    total_loss = correct = total = 0
    all_true, all_pred = [], []
    for imgs, labels in loader:
        imgs, labels = imgs.to(device), labels.to(device)
        out  = model(imgs)
        loss = criterion(out, labels)
        total_loss += loss.item() * imgs.size(0)
        preds       = out.argmax(1)
        correct    += (preds == labels).sum().item()
        total      += imgs.size(0)
        all_true.extend(labels.cpu().tolist())
        all_pred.extend(preds.cpu().tolist())
    return (
        total_loss / max(total, 1),
        correct    / max(total, 1),
        all_true, all_pred,
    )


# ═══════════════════════════════════════════════════════════════════════════
# STAGE 6 — Full split run
# ═══════════════════════════════════════════════════════════════════════════
def run_split(split_key: str, npz: dict, device: torch.device, epochs: int) -> None:
    cfg = SPLIT_CONFIGS[split_key]
    tag = cfg["tag"]
    seed_all(SEED)

    logger.info("\n" + "=" * 65)
    logger.info(
        f"  SPLIT {split_key}  "
        f"({int(cfg['train']*100)}/{int(cfg['val']*100)}/{int(cfg['test']*100)})"
    )
    logger.info("=" * 65)

    records = npz["records"]

    # Split on source images
    train_idx, val_idx, test_idx = split_npz(
        records, cfg["train"], cfg["val"], seed=SEED
    )

    # Assertions
    assert_no_leakage(train_idx, val_idx, test_idx, records, tag)

    # All classes in train
    tr_cls = {records[i]["cls"] for i in [records.index(r) for r in records if r["idx"] in set(train_idx)]}
    # faster lookup:
    idx_to_rec = {r["idx"]: r for r in records}
    tr_cls = {idx_to_rec[i]["cls"] for i in train_idx}
    missing = set(range(NUM_CLASSES)) - tr_cls
    assert not missing, f"[{tag}] Missing classes in train: {[KNOWN_USNS[c] for c in missing]}"
    logger.info(f"[{tag}] All {NUM_CLASSES} classes present in train.")

    print_class_dist(train_idx, val_idx, test_idx, records, tag)

    # Log split to file
    _write_split_log(train_idx, val_idx, test_idx, records, tag)

    # DataLoaders
    tr_loader, va_loader, te_loader = make_loaders(
        npz["images"], train_idx, val_idx, test_idx, records
    )
    logger.info(
        f"[{tag}] Loaders — "
        f"train batches={len(tr_loader)}  "
        f"val batches={len(va_loader)}  "
        f"test batches={len(te_loader)}"
    )

    # Model
    model     = ResNet50FaceClassifier(NUM_CLASSES).to(device)
    criterion = nn.CrossEntropyLoss()
    optimizer = optim.Adam(model.trainable_params(), lr=LR)
    scheduler = optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode="max", factor=0.5, patience=4
    )
    logger.info(
        f"[{tag}] Model — trainable: {model.n_trainable():,}  "
        f"frozen: {model.n_frozen():,}"
    )

    # Training loop
    history = {"train_loss": [], "train_acc": [], "val_loss": [], "val_acc": []}
    best_val_acc = -1.0
    best_state   = None
    patience_cnt = 0
    best_epoch   = 0

    for epoch in range(1, epochs + 1):
        t0 = time.time()
        tr_loss, tr_acc = train_epoch(model, tr_loader, criterion, optimizer, device)
        va_loss, va_acc, _, _ = eval_epoch(model, va_loader, criterion, device)
        scheduler.step(va_acc)

        history["train_loss"].append(tr_loss)
        history["train_acc"].append(tr_acc)
        history["val_loss"].append(va_loss)
        history["val_acc"].append(va_acc)

        flag = ""
        if va_acc > best_val_acc:
            best_val_acc = va_acc
            best_state   = copy.deepcopy(model.state_dict())
            patience_cnt = 0
            best_epoch   = epoch
            flag         = "  ** best"

        else:
            patience_cnt += 1

        logger.info(
            f"[{tag}] Epoch {epoch:03d}/{epochs}  "
            f"tr_loss={tr_loss:.4f}  tr_acc={tr_acc:.4f}  "
            f"vl_loss={va_loss:.4f}  vl_acc={va_acc:.4f}  "
            f"({time.time()-t0:.0f}s){flag}"
        )

        if patience_cnt >= PATIENCE:
            logger.info(
                f"[{tag}] Early stop at epoch {epoch}. "
                f"Best epoch {best_epoch} val_acc={best_val_acc:.4f}"
            )
            break

    # Save best model
    ckpt = RESULTS_DIR / f"best_model_{tag}.pth"
    torch.save({
        "epoch": best_epoch,
        "val_acc": best_val_acc,
        "model_state_dict": best_state,
        "class_names": KNOWN_USNS,
        "split": split_key,
    }, ckpt)
    logger.info(f"[{tag}] Checkpoint saved: {ckpt}")

    # ── Test evaluation (touched once) ───────────────────────────────────────
    model.load_state_dict(best_state)
    _, test_acc, test_true, test_pred = eval_epoch(
        model, te_loader, criterion, device
    )
    logger.info(f"[{tag}] TEST ACCURACY = {test_acc:.4f}")

    final_tr_acc = history["train_acc"][-1]
    gap = abs(final_tr_acc - test_acc)
    overfit_msg = ""
    if gap > 0.15:
        overfit_msg = (
            f"\nOVERFITTING WARNING: train/test gap = {gap*100:.1f}% (>15%)\n"
            f"  Final train acc = {final_tr_acc:.4f}  test acc = {test_acc:.4f}"
        )
        logger.warning(overfit_msg)

    # Per-class accuracy
    per_cls_correct = defaultdict(int)
    per_cls_total   = defaultdict(int)
    for t, p in zip(test_true, test_pred):
        per_cls_total[t]   += 1
        if t == p:
            per_cls_correct[t] += 1
    per_cls_lines = []
    for c, usn in enumerate(KNOWN_USNS):
        tot = per_cls_total[c]
        cor = per_cls_correct[c]
        acc = cor / tot if tot else float("nan")
        per_cls_lines.append(f"  {usn} (class {c:02d}): {cor}/{tot} = {acc:.4f}")

    clf_rep = classification_report(
        test_true, test_pred,
        target_names=KNOWN_USNS, digits=4, zero_division=0,
    )

    # Confusion matrix
    cm = confusion_matrix(test_true, test_pred, labels=list(range(NUM_CLASSES)))
    _save_confusion_matrix(cm, tag)

    # Training curves
    _save_training_curve(history, tag)

    # Results text
    _write_results(
        tag=tag, split_key=split_key, cfg=cfg,
        best_epoch=best_epoch, best_val_acc=best_val_acc,
        test_acc=test_acc, final_tr_acc=final_tr_acc,
        gap=gap, overfit_msg=overfit_msg,
        per_cls_lines=per_cls_lines, clf_rep=clf_rep,
        history=history,
        train_size=len(train_idx),
        val_size=len(val_idx),
        test_size=len(test_idx),
        epochs_run=len(history["train_loss"]),
    )

    logger.info(f"[{tag}] DONE. All outputs in {RESULTS_DIR}")


