def _save_confusion_matrix(cm: np.ndarray, tag: str) -> None:
    fig, ax = plt.subplots(figsize=(14, 12))
    im = ax.imshow(cm, cmap=plt.cm.Blues, interpolation="nearest")
    plt.colorbar(im, ax=ax)
    ticks      = np.arange(NUM_CLASSES)
    short      = [u[-5:] for u in KNOWN_USNS]
    ax.set_xticks(ticks); ax.set_xticklabels(short, rotation=45, ha="right", fontsize=8)
    ax.set_yticks(ticks); ax.set_yticklabels(short, fontsize=8)
    thresh = cm.max() / 2.0
    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            ax.text(j, i, str(cm[i, j]), ha="center", va="center",
                    fontsize=7, color="white" if cm[i,j] > thresh else "black")
    ax.set_xlabel("Predicted"); ax.set_ylabel("True")
    ax.set_title(f"Confusion Matrix — {tag} (Test Set)", fontsize=13)
    plt.tight_layout()
    out = RESULTS_DIR / f"confusion_matrix_{tag}.png"
    plt.savefig(out, dpi=150, bbox_inches="tight")
    plt.close(fig)
    logger.info(f"  Confusion matrix: {out}")


def _save_training_curve(history: dict, tag: str) -> None:
    epochs = list(range(1, len(history["train_loss"]) + 1))
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))
    ax1.plot(epochs, history["train_loss"], label="Train Loss", color="tab:blue")
    ax1.plot(epochs, history["val_loss"],   label="Val Loss",   color="tab:orange")
    ax1.set_xlabel("Epoch"); ax1.set_ylabel("Loss")
    ax1.set_title(f"Loss — {tag}"); ax1.legend(); ax1.grid(alpha=0.3)
    ax2.plot(epochs, [a*100 for a in history["train_acc"]], label="Train Acc", color="tab:blue")
    ax2.plot(epochs, [a*100 for a in history["val_acc"]],   label="Val Acc",   color="tab:orange")
    ax2.set_xlabel("Epoch"); ax2.set_ylabel("Accuracy (%)")
    ax2.set_title(f"Accuracy — {tag}"); ax2.legend(); ax2.grid(alpha=0.3); ax2.set_ylim(0, 105)
    plt.suptitle(f"VISTA ResNet-50 Training Curves — {tag}", fontsize=13)
    plt.tight_layout()
    out = RESULTS_DIR / f"training_curve_{tag}.png"
    plt.savefig(out, dpi=150, bbox_inches="tight")
    plt.close(fig)
    logger.info(f"  Training curve: {out}")


def _write_split_log(
    train_idx: list[int],
    val_idx:   list[int],
    test_idx:  list[int],
    records:   list[dict],
    tag: str,
) -> None:
    log_path = RESULTS_DIR / "data_split_npz_log.txt"
    idx_to_rec = {r["idx"]: r for r in records}
    with open(log_path, "a", encoding="utf-8") as f:
        f.write(f"\n{'='*65}\n")
        f.write(f"SPLIT {tag.upper()}  — {time.strftime('%Y-%m-%d %H:%M:%S')}\n")
        f.write(f"{'='*65}\n\n")
        for name, idxs in [("TRAIN", train_idx), ("VAL", val_idx), ("TEST", test_idx)]:
            f.write(f"--- {name} ({len(idxs)} samples) ---\n")
            for i in sorted(idxs):
                r = idx_to_rec[i]
                f.write(f"  [{r['usn']}]  {r['source']}  aug={r['aug_idx']}\n")
            f.write("\n")
    logger.info(f"  Split log appended: {log_path}")


def _write_results(
    tag, split_key, cfg,
    best_epoch, best_val_acc, test_acc, final_tr_acc,
    gap, overfit_msg, per_cls_lines, clf_rep, history,
    train_size, val_size, test_size, epochs_run,
) -> None:
    out = RESULTS_DIR / f"results_{tag}.txt"
    lines = [
        "=" * 65,
        "VISTA — ResNet-50 Face Classifier Results (trained from .npz)",
        "(backbone: ImageNet pretrained ResNet-50, ArcFace preprocessing)",
        f"Split {split_key}  ({int(cfg['train']*100)}/{int(cfg['val']*100)}/{int(cfg['test']*100)})",
        f"Generated: {time.strftime('%Y-%m-%d %H:%M:%S')}",
        "=" * 65, "",
        "DATA SOURCE",
        f"  NPZ: {NPZ_PATH}",
        f"  Train samples (all 30 aug variants): {train_size:,}",
        f"  Val  samples  (aug_idx==0 only)     : {val_size:,}",
        f"  Test samples  (aug_idx==0 only)     : {test_size:,}", "",
        "TRAINING CONFIG",
        f"  Epochs run         : {epochs_run}  (max {EPOCHS})",
        f"  Best epoch         : {best_epoch}",
        f"  Early stop patience: {PATIENCE}",
        f"  Batch size         : {BATCH_SIZE}",
        f"  Learning rate      : {LR}",
        f"  Optimizer          : Adam",
        f"  Loss               : CrossEntropyLoss",
        f"  Backbone           : ResNet-50 (ImageNet, NOT ArcFace ONNX)",
        f"  Input size         : 112x112, mean=0.5 std=0.5", "",
        "ACCURACY SUMMARY",
        f"  Best val accuracy  : {best_val_acc*100:.2f}%",
        f"  Final train acc    : {final_tr_acc*100:.2f}%",
        f"  Test accuracy      : {test_acc*100:.2f}%",
        f"  Train/Test gap     : {gap*100:.2f}%",
    ]
    if overfit_msg:
        lines.append(overfit_msg)
    lines += ["", "EPOCH LOG (train_loss | train_acc | val_loss | val_acc)", "-" * 60]
    for ep, (tl, ta, vl, va) in enumerate(zip(
        history["train_loss"], history["train_acc"],
        history["val_loss"],   history["val_acc"],
    ), 1):
        lines.append(f"  Epoch {ep:03d}:  {tl:.4f} | {ta:.4f} | {vl:.4f} | {va:.4f}")
    lines += ["", "PER-CLASS TEST ACCURACY", "-" * 60]
    lines += per_cls_lines
    lines += ["", "CLASSIFICATION REPORT", "-" * 60, clf_rep, "", "=" * 65, "END"]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    logger.info(f"  Results written: {out}")


